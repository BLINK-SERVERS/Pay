const PIXELES: Record<Exclude<TamanoSimbolo, number>, number> = {
  xs: 12,
  sm: 16,
  md: 20,
  lg: 24,
  xl: 32,
};

export interface Props extends Omit<SVGProps<SVGSVGElement>, "name"> {
  nombre: NombreSimbolo;
  variante?: VarianteSimbolo;
  tamano?: TamanoSimbolo;
  animacion?: AnimacionSimbolo;
  /** Color de la capa de fondo en las variantes de paleta. */
  colorSecundario?: string;
  /** Color de la capa principal en multicolor. */
  colorPrincipal?: string;
  /** Color de las capas intermedias en multicolor. */
  colorTerciario?: string;
  /** Nombre accesible. Sin él, el símbolo queda oculto a lectores. */
  titulo?: string;
}

export function BlinkSymbol({
  nombre,
  variante = "jerarquico",
  tamano = "md",
  animacion = "ninguna",
  colorSecundario,
  colorPrincipal,
  colorTerciario,
  titulo,
  className = "",
  style,
  ...resto
}: Props) {
  const par = ICONOS[nombre];
  const Componente = variante === "monocromo" ? par.monocromo : par.jerarquico;
  const clases = [
    "simbolo",
    "icon",
    animacion !== "ninguna" ? `simbolo--${animacion}` : "",
    className,
  ]
    .filter(Boolean)
    .join(" ");

  const variables: CSSProperties = {
    ...style,
    ...(colorSecundario ? { "--simbolo-secundario": colorSecundario } : null),
    ...(colorPrincipal ? { "--simbolo-principal": colorPrincipal } : null),
    ...(colorTerciario ? { "--simbolo-terciario": colorTerciario } : null),
  } as CSSProperties;

  const props = {
    size: typeof tamano === "number" ? tamano : PIXELES[tamano],
    className: clases,
    style: variables,
    "data-variante": variante,
    focusable: false,
    "aria-hidden": titulo ? undefined : true,
    role: titulo ? "img" : undefined,
    "aria-label": titulo,
    ...resto,
  };

  return <Componente {...props} />;
}
